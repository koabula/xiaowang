import assert from "node:assert/strict";
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { test } from "node:test";
import { Runtime } from "../src/runtime.ts";
import { JobQueue } from "../src/jobs.ts";

test("deleted bots revoke access, retain local files, protect the steward and survive restart", t => {
  const home = mkdtempSync(path.join(tmpdir(), "xw-delete-"));
  let runtime = Runtime.open(home);
  t.after(() => { runtime.close(); rmSync(home, { recursive: true, force: true }); });
  const steward = runtime.activeBot();
  const bot = runtime.store.createBot({ name: "Research", systemPrompt: "test" });
  const child = runtime.store.createBot({ name: "Child", systemPrompt: "test", parentBotId: bot.id });
  runtime.store.append(bot.id, { type: "baseline", text: "private-history" });
  const ref = runtime.store.addLibraryBytes(bot.id, "shared.md", Buffer.from("shared-bytes")).ref;
  runtime.store.addLibraryBytes(steward.id, "shared.md", Buffer.from("shared-bytes"));
  writeFileSync(path.join(bot.workspaceDir, "note.md"), "retained");
  runtime.store.setActiveBot(bot.id);
  runtime.store.renameBot(bot.id, "Renamed");
  assert.equal(runtime.store.requireBot(bot.id).slug, bot.slug);
  assert.throws(() => runtime.store.renameBot(bot.id, " "), /不能为空/);
  assert.throws(() => runtime.store.deleteBot(steward.id), /主助手/);
  runtime.store.deleteBot(bot.id);
  assert.equal(runtime.activeBot().id, steward.id);
  assert.equal(runtime.store.getBot(bot.id), null);
  assert.equal(runtime.store.requireBot(child.id).parentBotId, steward.id);
  assert.throws(() => runtime.store.getEvents(bot.id), /没有这个/);
  assert.throws(() => runtime.store.listLibrary(bot.id), /没有这个/);
  assert.equal(runtime.store.resolveLibraryRef(steward.id, ref.id).id, ref.id);
  assert.equal(existsSync(path.join(bot.workspaceDir, "note.md")), true);
  const replacement = runtime.store.createBot({ name: "Research", systemPrompt: "new" });
  assert.notEqual(replacement.slug, bot.slug, "Never reuse a deleted workspace or its private files");
  runtime.close(); runtime = Runtime.open(home);
  assert.equal(runtime.store.getBot(bot.slug), null);
  assert.equal(runtime.store.listBots().length, 3);
});

test("delete drains active work before revoking access and never starts queued work", async t => {
  const home = mkdtempSync(path.join(tmpdir(), "xw-delete-jobs-"));
  const runtime = Runtime.open(home);
  const bot = runtime.store.createBot({ name: "Busy", systemPrompt: "test" });
  let entered!: () => void; const started = new Promise<void>(resolve => { entered = resolve; });
  let cleanup!: () => void; const release = new Promise<void>(resolve => { cleanup = resolve; });
  const runs: string[] = [];
  const queue = new JobQueue(runtime.store, async (job, signal) => {
    runs.push(job.task); entered();
    await new Promise<void>(resolve => signal.addEventListener("abort", () => resolve(), { once: true }));
    await release;
    runtime.store.append(bot.id, { type: "baseline", text: "cleanup completed before deletion" });
    return { text: "late completion must not succeed" };
  });
  t.after(() => { queue.shutdown(); runtime.close(); rmSync(home, { recursive: true, force: true }); });
  queue.start();
  const first = queue.enqueue({ botId: bot.id, task: "running" });
  const second = queue.enqueue({ botId: bot.id, task: "queued" });
  await started;
  const waiting = queue.wait(first.id);
  let drained = false;
  assert.throws(() => queue.forgetBot(bot.id), /先删除/);
  const deletion = queue.prepareBotDeletion(bot.id).then(() => { drained = true; runtime.store.deleteBot(bot.id); queue.forgetBot(bot.id); });
  assert.equal((await waiting).status, "cancelled");
  assert.equal(queue.get(second.id).status, "cancelled");
  assert.throws(() => queue.enqueue({ botId: bot.id, task: "late" }), /正在删除/);
  await Promise.resolve(); assert.equal(drained, false);
  cleanup(); await deletion;
  assert.deepEqual(runs, ["running"]);
  assert.deepEqual(queue.list(bot.id), []);
  assert.equal(runtime.store.getBot(bot.id), null);
});

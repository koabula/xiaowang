import { electron, closeTestApp } from './launch.mjs';
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createServer } from 'node:http';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(check) { for (let n = 0; n < 200; n++) { const value = await check(); if (value) return value; await sleep(30); } throw Error('Condition timed out'); }

test('composer, new-bot thinking, sidebar rename/delete and persistence', { timeout: 60000 }, async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'xw-bot-actions-'));
  const profile = path.join(root, 'profile'); await mkdir(profile);
  let release; const gate = new Promise(resolve => { release = resolve; });
  let releaseManual; const manualGate = new Promise(resolve => { releaseManual = resolve; });
  const server = createServer(async (req, res) => {
    if (req.method === 'GET') { res.end('<!doctype html><title>Private bot browser</title><p>PRIVATE-BOT-PAGE</p>'); return; }
    let raw = ''; for await (const part of req) raw += part;
    const body = JSON.parse(raw); const last = body.messages.findLast(item => item.role === 'user')?.content || '';
    const spawnIds = new Set(body.messages.flatMap(item => item.tool_calls ?? []).filter(call => call.function?.name === 'spawn_bot').map(call => call.id));
    const spawned = body.messages.some(item => item.role === 'tool' && spawnIds.has(item.tool_call_id));
    res.writeHead(200, { 'content-type': 'text/event-stream' });
    let delta;
    if (last.includes('CREATE-CHILD') && !spawned) delta = { tool_calls: [{ index: 0, id: 'spawn-test', function: { name: 'spawn_bot', arguments: JSON.stringify({ name: 'Research child', baseline: 'Separate topic', kickoff_task: 'CHILD-KICKOFF' }) } }] };
    else { if (last.includes('CHILD-KICKOFF')) await gate; if (last.includes('MANUAL-WORK')) await manualGate; delta = { content: 'WORK-DONE' }; }
    res.end(`data: ${JSON.stringify({ choices: [{ delta, finish_reason: delta.tool_calls ? 'tool_calls' : 'stop' }] })}\n\ndata: [DONE]\n\n`);
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  await writeFile(path.join(profile, 'secrets.bin'), JSON.stringify({ baseUrl: `http://127.0.0.1:${server.address().port}/v1`, model: 'fixture', apiKey: 'local', locale: 'zh' }));
  const env = { ...process.env, XIAOWANG_HOME: path.join(root, 'home'), XIAOWANG_USER_DATA: profile, XIAOWANG_DISABLE_UPDATES: '1' }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ args: ['--no-sandbox', 'desktop/dist/main.js'], env });
  t.after(async () => { release(); releaseManual(); await closeTestApp(app); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await rm(root, { recursive: true, force: true, maxRetries: 10 }); });
  const page = await app.firstWindow(); page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const textarea = page.locator('.composer textarea'); await textarea.waitFor();
  const stewardAvatar = page.locator('.steward .avatar');
  assert.equal(await stewardAvatar.locator('rect[transform]').getAttribute('transform'), 'translate(9 9) rotate(199 18 18) scale(1.1)');
  assert.equal(await stewardAvatar.locator('rect[transform]').getAttribute('fill'), '#2B59C3');
  assert.equal(await stewardAvatar.locator('g > g').getAttribute('transform'), 'translate(4.5 4.5) rotate(-9 18 18)');
  await textarea.focus(); assert.equal(await textarea.evaluate(node => getComputedStyle(node).outlineStyle), 'none');
  const short = await textarea.evaluate(node => node.clientHeight);
  await textarea.fill('line\n'.repeat(30)); const tall = await textarea.evaluate(node => node.clientHeight);
  assert.ok(tall > short && tall <= 144); assert.ok(await textarea.evaluate(node => node.scrollHeight > node.clientHeight));
  await textarea.fill('CREATE-CHILD'); assert.equal(await textarea.evaluate(node => node.clientHeight), short);
  await textarea.press('Enter');
  const child = await until(async () => (await page.evaluate(() => window.xiaowang.getState())).bots.find(bot => bot.name === 'Research child'));
  assert.equal((await page.evaluate(() => window.xiaowang.getState())).bots.filter(bot => bot.name === 'Research child').length, 1);
  const row = page.locator('.bot').filter({ hasText: 'Research child' }); await row.click();
  await page.locator('.thinking .avatar.think').waitFor(); assert.equal(await page.locator('.thinking .dots i').count(), 3);
  await until(() => row.evaluate(node => node.classList.contains('working')));
  await page.reload(); await page.locator('.thinking .avatar.think').waitFor();
  assert.equal(await page.locator('.task-item').count(), 0);
  await row.click({ button: 'right' });
  const menu = page.getByRole('menu', { name: 'Bot 操作' }); await menu.waitFor();
  assert.equal(await menu.getByRole('menuitem').count(), 2);
  await page.screenshot({ path: path.join(os.tmpdir(), 'xiaowang-bot-menu.png') });
  await page.keyboard.press('Escape'); await menu.waitFor({ state: 'detached' });
  await row.click({ button: 'right' }); await menu.getByRole('menuitem', { name: '重命名', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '重命名 Bot', exact: true });
  await dialog.getByRole('textbox').fill('   '); assert.equal(await dialog.getByRole('button', { name: '保存', exact: true }).isDisabled(), true);
  await dialog.getByRole('textbox').fill('Renamed child'); await dialog.getByRole('textbox').press('Enter');
  await page.locator('.bot').filter({ hasText: 'Renamed child' }).waitFor();
  assert.equal((await page.evaluate(() => window.xiaowang.getState())).activeSlug, child.slug);
  release(); await page.locator('.thinking').waitFor({ state: 'detached' });
  assert.equal(await page.locator('.task-item').count(), 0);
  const manualSlug = await page.evaluate(() => window.xiaowang.createBot('Manual bot', 'test'));
  await until(async () => (await page.evaluate(() => window.xiaowang.getState())).activeSlug === manualSlug);
  await textarea.fill('MANUAL-WORK'); await textarea.press('Enter');
  await page.locator('.thinking .avatar.think').waitFor();
  const manual = page.locator('.bot').filter({ hasText: 'Manual bot' });
  await until(() => manual.evaluate(node => node.classList.contains('working')));
  await manual.focus(); await page.keyboard.press('Shift+F10');
  await menu.waitFor(); await page.keyboard.press('ArrowDown');
  assert.equal(await menu.getByRole('menuitem', { name: '删除', exact: true }).evaluate(node => node === document.activeElement), true);
  await page.keyboard.press('Escape'); await menu.waitFor({ state: 'detached' });
  await page.evaluate(async url => { await window.xiaowang.browserHolder('user'); await window.xiaowang.browserGo(url); }, `http://127.0.0.1:${server.address().port}/private`);
  await manual.click({ button: 'right' });
  await menu.getByRole('menuitem', { name: '删除', exact: true }).click();
  await page.getByRole('dialog', { name: '删除 Bot？' }).getByRole('button', { name: '取消', exact: true }).click();
  assert.ok((await page.evaluate(() => window.xiaowang.getState())).bots.some(bot => bot.slug === manualSlug));
  await manual.click({ button: 'right' }); await menu.getByRole('menuitem', { name: '删除', exact: true }).click();
  await page.getByRole('dialog', { name: '删除 Bot？' }).getByRole('button', { name: '删除', exact: true }).click();
  await manual.waitFor({ state: 'detached' });
  releaseManual();
  assert.equal((await page.evaluate(() => window.xiaowang.getState())).jobs.some(job => job.slug === manualSlug), false);
  await page.reload(); await textarea.waitFor();
  const state = await page.evaluate(() => window.xiaowang.getState());
  assert.equal(state.activeSlug, 'xiaowang'); assert.equal(state.bots.some(bot => bot.slug === manualSlug), false);
  assert.equal(state.browser.url, '', 'Deletion clears the deleted bot browser page and history'); assert.equal(state.browser.holder, 'bot');
  assert.equal(state.bots.find(bot => bot.slug === child.slug).name, 'Renamed child');
  await page.locator('.steward').click({ button: 'right' });
  assert.equal(await menu.getByRole('menuitem', { name: '删除', exact: true }).isDisabled(), true);
  await assert.rejects(page.evaluate(() => window.xiaowang.deleteBot('xiaowang')), /主助手/);
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.xiaowang.setAvatar('xiaowang', { seed: 'custom-face', ink: '#177E6B' }));
  await page.reload(); await textarea.waitFor();
  assert.equal(await stewardAvatar.locator('rect[transform]').getAttribute('fill'), '#177E6B');
  assert.equal((await page.evaluate(() => window.xiaowang.getState())).bots.find(bot => bot.slug === 'xiaowang').avatarSeed, 'custom-face');
  assert.deepEqual(errors, []);
});

import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createServer } from 'node:http';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { _electron as electron } from 'playwright';
import { closeTestApp } from './launch.mjs';

test('desktop: MOSS is hidden and blocked by default, saved profiles survive migration, save and restart', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'xw-moss-disabled-')), profile = path.join(root, 'profile'); await mkdir(profile);
  let requests = 0;
  const catalog = createServer((_req, res) => { requests++; res.writeHead(500); res.end(); });
  await new Promise(resolve => catalog.listen(0, '127.0.0.1', resolve));
  await writeFile(path.join(profile, 'secrets.bin'), JSON.stringify({ model: 'fixture', baseUrl: 'http://127.0.0.1:1/v1', apiKey: 'text-fixture', realtimeService: 'moss', realtimeKey: 'moss-private-2222', realtimeVoice: 'custom-moss-voice', realtimeProfiles: { doubao: { key: 'doubao-private-3333', voice: 'zh_male_m191_uranus_bigtts' } } }));
  const env = { ...process.env, XIAOWANG_HOME: path.join(root, 'home'), XIAOWANG_USER_DATA: profile, XIAOWANG_DISABLE_UPDATES: '1', XIAOWANG_MOSS_VOICES_URL: `http://127.0.0.1:${catalog.address().port}/voices` };
  for (const name of Object.keys(env)) if (name === 'ELECTRON_RUN_AS_NODE' || name === 'XIAOWANG_ENABLE_MOSS' || name.startsWith('XIAOWANG_REALTIME_')) delete env[name];
  let app, page; const errors = [];
  const launch = async () => {
    app = await electron.launch({ args: ['--no-sandbox', '--use-mock-keychain', 'desktop/dist/main.js'], env });
    page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message)); await page.waitForSelector('.composer');
  };
  t.after(async () => { if (app) await closeTestApp(app); catalog.closeAllConnections(); await new Promise(resolve => catalog.close(resolve)); await rm(root, { recursive: true, force: true, maxRetries: 10 }); });
  await launch();
  let state = await page.evaluate(() => window.xiaowang.getState());
  assert.equal(state.settings.experimentalMossEnabled, false); assert.equal(state.settings.realtimeService, 'doubao');
  assert.match(state.settings.realtimeKeyHint, /3333/); assert.match(state.settings.realtimeProfiles.moss.keyHint, /2222/);
  assert.ok(!JSON.stringify(state.settings).includes('moss-private')); assert.ok(!JSON.stringify(state.settings).includes('doubao-private'));
  await page.locator('button.settings').click(); const settings = page.getByRole('form', { name: '设置', exact: true }); await settings.waitFor();
  assert.match(await settings.getByRole('combobox', { name: '服务', exact: true }).innerText(), /豆包/);
  await settings.getByRole('combobox', { name: '服务', exact: true }).click();
  assert.equal(await page.getByRole('option').count(), 4); assert.equal(await page.getByRole('option', { name: 'MOSS Live', exact: true }).count(), 0);
  for (const name of ['通义千问', 'OpenAI', '豆包全双工', 'Gemini Live']) assert.equal(await page.getByRole('option', { name, exact: true }).count(), 1);
  await page.keyboard.press('Escape'); await page.getByRole('listbox').waitFor({ state: 'detached' });
  assert.equal(await settings.getByRole('searchbox', { name: '搜索音色' }).count(), 0);
  await assert.rejects(page.evaluate(() => window.xiaowang.previewVoice({ realtimeService: 'moss' })), /暂时停用/);
  await assert.rejects(page.evaluate(() => window.xiaowang.saveSettings({ realtimeService: 'moss' })), /暂时停用/);
  await assert.rejects(page.evaluate(() => window.xiaowang.listVoices({ realtimeService: 'moss' }, true)), /暂时停用/);
  assert.equal(requests, 0, 'Disabled MOSS must not fetch voices');
  await settings.getByRole('button', { name: '保存并进入', exact: true }).click(); await settings.waitFor({ state: 'detached' });
  await closeTestApp(app); await launch(); state = await page.evaluate(() => window.xiaowang.getState());
  assert.equal(state.settings.realtimeService, 'doubao'); assert.match(state.settings.realtimeKeyHint, /3333/); assert.match(state.settings.realtimeProfiles.moss.keyHint, /2222/);
  await closeTestApp(app); app = null;
  await writeFile(path.join(profile, 'secrets.bin'), JSON.stringify({ model: 'fixture', baseUrl: 'http://127.0.0.1:1/v1', apiKey: 'text-fixture', realtimeService: 'moss', realtimeKey: 'moss-only-4444' }));
  await launch(); state = await page.evaluate(() => window.xiaowang.getState());
  assert.equal(state.settings.realtimeService, 'qwen'); assert.equal(state.settings.realtimeKeyHint, ''); assert.match(state.settings.realtimeProfiles.moss.keyHint, /4444/);
  await assert.rejects(page.evaluate(() => window.xiaowang.callStart('xiaowang')), /密钥/);
  assert.equal(requests, 0); assert.deepEqual(errors, []);
});
